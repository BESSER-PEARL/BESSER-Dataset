





import java.util.List;
import java.util.ArrayList;

public class Trapezoidal  {

    private float D;
    private float E;



    public Trapezoidal(
        float D,        float E    ) {
        this.D = D;
        this.E = E;
    }


    public float getD() {
        return D;
    }

    public void setD(float D) {
        this.D = D;
    }
    public float getE() {
        return E;
    }

    public void setE(float E) {
        this.E = E;
    }


}