





import java.util.List;
import java.util.ArrayList;

public class ram_LayoutElement  {

    private float x;
    private float y;



    public ram_LayoutElement(
        float x,        float y    ) {
        this.x = x;
        this.y = y;
    }


    public float getX() {
        return x;
    }

    public void setX(float x) {
        this.x = x;
    }
    public float getY() {
        return y;
    }

    public void setY(float y) {
        this.y = y;
    }


}