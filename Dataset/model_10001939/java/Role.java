





import java.util.List;
import java.util.ArrayList;

public class Role  {

    private String descripcion;
    private None nombre;
    private None Name;



    public Role(
        String descripcion,        None nombre,        None Name    ) {
        this.descripcion = descripcion;
        this.nombre = nombre;
        this.Name = Name;
    }


    public String getDescripcion() {
        return descripcion;
    }

    public void setDescripcion(String descripcion) {
        this.descripcion = descripcion;
    }
    public None getNombre() {
        return nombre;
    }

    public void setNombre(None nombre) {
        this.nombre = nombre;
    }
    public None getName() {
        return Name;
    }

    public void setName(None Name) {
        this.Name = Name;
    }


}