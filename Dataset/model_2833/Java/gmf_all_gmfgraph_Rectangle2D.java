





import java.util.List;
import java.util.ArrayList;

public class gmf_all_gmfgraph_Rectangle2D  {

    private float y;
    private float width;
    private float x;
    private float height;



    public gmf_all_gmfgraph_Rectangle2D(
        float y,        float width,        float x,        float height    ) {
        this.y = y;
        this.width = width;
        this.x = x;
        this.height = height;
    }


    public float getY() {
        return y;
    }

    public void setY(float y) {
        this.y = y;
    }
    public float getWidth() {
        return width;
    }

    public void setWidth(float width) {
        this.width = width;
    }
    public float getX() {
        return x;
    }

    public void setX(float x) {
        this.x = x;
    }
    public float getHeight() {
        return height;
    }

    public void setHeight(float height) {
        this.height = height;
    }


}