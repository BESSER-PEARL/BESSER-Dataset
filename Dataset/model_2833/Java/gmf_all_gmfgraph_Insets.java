





import java.util.List;
import java.util.ArrayList;

public class gmf_all_gmfgraph_Insets  {

    private int bottom;
    private int top;
    private int right;
    private int left;



    public gmf_all_gmfgraph_Insets(
        int bottom,        int top,        int right,        int left    ) {
        this.bottom = bottom;
        this.top = top;
        this.right = right;
        this.left = left;
    }


    public int getBottom() {
        return bottom;
    }

    public void setBottom(int bottom) {
        this.bottom = bottom;
    }
    public int getTop() {
        return top;
    }

    public void setTop(int top) {
        this.top = top;
    }
    public int getRight() {
        return right;
    }

    public void setRight(int right) {
        this.right = right;
    }
    public int getLeft() {
        return left;
    }

    public void setLeft(int left) {
        this.left = left;
    }


}