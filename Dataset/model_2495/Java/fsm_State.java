





import java.util.List;
import java.util.ArrayList;

public class fsm_State  {

    private float d;
    private String foo;
    private String c;
    private float f;
    private boolean b;
    private String l;
    private int i;



    public fsm_State(
        float d,        String foo,        String c,        float f,        boolean b,        String l,        int i    ) {
        this.d = d;
        this.foo = foo;
        this.c = c;
        this.f = f;
        this.b = b;
        this.l = l;
        this.i = i;
    }


    public float getD() {
        return d;
    }

    public void setD(float d) {
        this.d = d;
    }
    public String getFoo() {
        return foo;
    }

    public void setFoo(String foo) {
        this.foo = foo;
    }
    public String getC() {
        return c;
    }

    public void setC(String c) {
        this.c = c;
    }
    public float getF() {
        return f;
    }

    public void setF(float f) {
        this.f = f;
    }
    public boolean getB() {
        return b;
    }

    public void setB(boolean b) {
        this.b = b;
    }
    public String getL() {
        return l;
    }

    public void setL(String l) {
        this.l = l;
    }
    public int getI() {
        return i;
    }

    public void setI(int i) {
        this.i = i;
    }


}